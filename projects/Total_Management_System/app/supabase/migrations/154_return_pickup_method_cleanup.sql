-- 154: 반품·교환 회수 방법 용어 통일 (사장님 확정 2026-09-17)
--
-- 배경 — 같은 걸 가리키는 이름이 세 곳에서 제각각이었다
--   반품·교환 모달        : 'store' | '방문수거' | '택배수거' | '직접반납'
--   주문 교환 API 주석    : '직접수거' | '방문수거' | '택배수거' | '고객반납'
--   주문 교환 API 기본값  : '직접수거'
--   실제 DB               : '택배수거' | '직접수거'
--
--   사장님: "직접반납이라는 용어도 내가 뭔지 이해가 하나도 안되는 단어이고,
--            직접수거는 내가 복원수리 방문수거 접수때 쓰던이름이고,
--            고객반납은 ... 이것도 첨듣는 단어야"
--   → 누가 누구한테서 받는지가 드러나지 않아 읽히지 않는 이름들이었다.
--
-- 확정 — 회수 방법은 2가지 (+ 즉시수령은 애초에 반품 건이 안 생김)
--   '택배수거'  : 롯데 기사가 고객집 방문 회수  → 고객 알림톡 O ("문 앞에 놓아주세요")
--   '대면수령'  : 사장님이 만나서 직접 받음      → 고객 알림톡 X (이미 만나서 얘기함)
--
--   ❌ '방문수거' 폐기 — 사장님이 가서 받아오는 경우는 거의 없고,
--      '방문수거'는 복원수리에서 **고객이 가위를 보내는 방법** 이름이라 뜻이 충돌한다.

-- ─────────────────────────────────────────────
-- 1) 기존 값 정리 — 택배수거를 뺀 나머지는 전부 대면수령
-- ─────────────────────────────────────────────
UPDATE returns
SET    pickup_method = '대면수령'
WHERE  pickup_method IS NOT NULL
  AND  pickup_method NOT IN ('택배수거', '대면수령');

-- ─────────────────────────────────────────────
-- 2) 확인용 (실행 후 눈으로 보기)
-- ─────────────────────────────────────────────
SELECT COALESCE(pickup_method, '(없음)') AS "회수 방법",
       COUNT(*)                          AS "건수"
FROM   returns
GROUP  BY pickup_method
ORDER  BY 2 DESC;
