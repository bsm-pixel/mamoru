-- 115: 단 번호 의미 정정 — 1단 = 맨 아래 (2026-07-18)
--
-- 배경: 112~114 는 1단을 '맨 위'로 잡았는데, 한국에서 렉·선반의 단은
--   건물 층수처럼 **아래에서 위로** 세는 게 자연스럽다(1단=맨 아래).
--   사장님 지적: "5단이면 1단이 맨 하단 아닌가? 1단이 맨 위에 있어서 이질감 든다"
--
-- 변경 내용:
--   · level_no 의 '의미'가 뒤집힌다 (1 = 맨 아래). **데이터는 바꾸지 않는다.**
--     화면에서 큰 번호가 위에 오도록 역순으로 그리는 것으로 해결 (코드/자리 번호 불변)
--   · 라벨의 '상단/중단/하단' 표기를 폐지하고 'N단' 으로 통일
--     (3단일 때만 상/중/하를 쓰던 규칙이 단 수가 달라지면 깨지고 헷갈리기만 했음)
--
-- ⚠️ 자리 코드(R01-1-A 등)는 전혀 바뀌지 않는다. 이미 출력한 라벨의 '코드'는 그대로 유효.
--    다만 "1단"이 가리키는 물리적 선반이 위→아래로 바뀌므로,
--    실물에 단 번호를 이미 써 붙였다면 위아래를 뒤집어야 한다(아래 안내 참고).
--
-- 되돌리기: 라벨 표기만의 변경이라 되돌릴 필요가 거의 없음.

-- 기존 라벨의 상단/중단/하단 → 'N단' 으로 치환 (행의 level_no 사용)
UPDATE warehouse_locations
   SET label = regexp_replace(label, '(상단|중단|하단)', level_no || '단')
 WHERE label ~ '(상단|중단|하단)';

COMMENT ON COLUMN warehouse_locations.level_no IS
  '단 번호. 1 = 맨 아래(건물 층수와 같은 감각). 화면은 큰 번호가 위 (115, 2026-07-18)';
