/**
 * 목록 옆 상세 칸 — 폭이 좁은 PC(세로로 세운 모니터 · 노트북, 1024~1535)에서 자리 쓰는 법 (2026-11-22)
 *
 * 실제 사고: 세로 모니터(폭 약 1,060)에서 「목록에서 건을 선택하세요」만 있는 빈 칸이 440px 을 차지해
 *   목록이 500px 로 눌렸고, 상태 · 금액 · 전화번호가 글자 단위로 세로로 꺾였다.
 *
 * 규칙: 아무것도 고르지 않았으면 빈 칸을 접어 목록이 화면 전체를 쓴다. 건을 고르면 상세가 열린다.
 *   1536 이상(보통의 가로 모니터)은 전과 같다 — 빈 칸이 그대로 있어 고를 때 화면이 움직이지 않는다.
 * 글자를 줄이지 않는 이유: 500px 에 8칸을 넣으려면 글자가 8px 까지 내려가 읽을 수 없다. 부족한 것은 글자 크기가 아니라 자리다.
 *
 * 쓰는 법: 상세 칸 div 의 className 에 `${emptyPaneCls(!!selectedId)}` 를 더한다.
 */
export function emptyPaneCls(hasSelection: boolean): string {
  return hasSelection ? '' : 'max-[1535px]:hidden';
}
